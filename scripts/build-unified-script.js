const fs = require("node:fs");
const path = require("node:path");
const prettier = require("prettier");

const ROOT = path.join(__dirname, "..");
const OUTPUT = path.join(ROOT, "LoL-Esports-Schedule.js");

function read(file) {
  return fs.readFileSync(path.join(ROOT, file), "utf8");
}

function wrapModule(name, source) {
  return `const ${name} = (() => {\n  const module = { exports: {} };\n${source}\n  return module.exports;\n})();\n`;
}

function replaceOnce(source, needle, replacement) {
  if (
    !source.includes(needle) ||
    source.indexOf(needle) !== source.lastIndexOf(needle)
  )
    throw new Error(
      `Unified source anchor missing or repeated: ${needle.slice(0, 60)}`
    );
  return source.replace(needle, replacement);
}

function buildUnifiedSource() {
  const original = read("LPL-Schedule.js");
  const productVersion = JSON.parse(read("package.json")).version;
  const header = original.match(
    /^(\/\/ Variables used by Scriptable\.\r?\n\/\/ These must be at the very top of the file\. Do not edit\.\r?\n\/\/ icon-color: [^\r\n]+; icon-glyph: [^\r\n]+;\r?\n)/
  )?.[1];
  if (!header) throw new Error("Scriptable metadata missing");
  let body = original.slice(header.length);
  const oldTheme = `let DesignSystem;
try {
  DesignSystem = importModule(
    IS_DEV ? DEV_RUNTIME.designSystemModule : "LPL-Design-System"
  );
} catch (error) {
  throw new Error(
    IS_DEV
      ? "缺少 LPL-Design-System-DEV。请重新运行 Installer-Dev.js。"
      : "缺少 LPL-Design-System。请复制并运行仓库中的最新版 Installer.js 完成安装。"
  );
}`;
  body = replaceOnce(body, oldTheme, "const DesignSystem = UNIFIED_THEME;");
  body = replaceOnce(
    body,
    'converter = importModule("LPL-Cito-Worlds");',
    "converter = UNIFIED_CITO;"
  );
  body = replaceOnce(
    body,
    'personal = importModule("LPL-Cito-Personal");',
    "personal = UNIFIED_PERSONAL;"
  );
  body = replaceOnce(
    body,
    "await presentSettings();",
    "await presentUnifiedSettings();"
  );
  const appIdentity = /name: "LPL Schedule",\s*version: "\d+\.\d+\.\d+",/g;
  if ([...body.matchAll(appIdentity)].length !== 1)
    throw new Error("Unified product identity anchor missing or repeated");
  body = body.replace(
    appIdentity,
    `name: "英雄联盟比赛赛程表",\n  version: "${productVersion}",`
  );
  body = replaceOnce(
    body,
    'title: "LPL SCHEDULE",',
    'title: "英雄联盟比赛赛程表",'
  );
  body = replaceOnce(
    body,
    "seasonText: `${SEASON.year} ${SEASON.stage}`,",
    'seasonText: "英雄联盟赛事",'
  );
  if (/\bimportModule\s*\(/.test(body))
    throw new Error("Runtime module import remains in unified script");
  return [
    header,
    "// Generated by scripts/build-unified-script.js. Edit the source files, then rebuild.\n",
    wrapModule(
      "UNIFIED_THEME",
      read("LPL-Design-System.js").replace(
        /\* 可供其他 Scriptable 项目通过 importModule\([^\n]+\n/,
        "* 内嵌的显示主题与布局规范。\n"
      )
    ),
    wrapModule("UNIFIED_CITO", read("LPL-Cito-Worlds.js")),
    wrapModule("UNIFIED_PERSONAL", read("LPL-Cito-Personal.js")),
    body,
  ].join("\n");
}

if (require.main === module) {
  prettier
    .resolveConfig(OUTPUT)
    .then((options) =>
      prettier.format(buildUnifiedSource(), { ...options, parser: "babel" })
    )
    .then((formatted) => {
      fs.writeFileSync(OUTPUT, formatted, "utf8");
      console.log(OUTPUT);
    })
    .catch((error) => {
      console.error(error);
      process.exitCode = 1;
    });
}

module.exports = { buildUnifiedSource, OUTPUT };
